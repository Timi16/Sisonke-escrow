/**
 * Copies the public deployment facts from ../deployments into lib/generated/,
 * so web/ builds on its own (for example with Vercel's root set to web/).
 *
 *   pnpm sync    # after scripts/deploy.sh or scripts/e2e.ts changed deployments/
 *
 * Every value is public. tests/config.test.ts fails when these drift.
 */
import { copyFileSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const WEB = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DEPLOYMENTS = path.resolve(WEB, "../deployments");

/** Parses KEY=value lines, dropping comments and surrounding quotes. */
export function parseEnv(text) {
  const out = {};
  for (const line of text.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#") || !trimmed.includes("=")) continue;
    const key = trimmed.slice(0, trimmed.indexOf("="));
    let value = trimmed.slice(trimmed.indexOf("=") + 1);
    if (/^".*"$/.test(value)) value = value.slice(1, -1);
    out[key] = value;
  }
  return out;
}

export const KEYS = [
  "NEXT_PUBLIC_STELLAR_NETWORK",
  "NEXT_PUBLIC_NETWORK_PASSPHRASE",
  "NEXT_PUBLIC_RPC_URL",
  "NEXT_PUBLIC_HORIZON_URL",
  "NEXT_PUBLIC_EXPLORER_URL",
  "NEXT_PUBLIC_SISONKE_CONTRACT_ID",
  "NEXT_PUBLIC_USDC_SAC_ID",
  "NEXT_PUBLIC_USDC_ISSUER",
  "NEXT_PUBLIC_SISONKE_DEPLOY_LEDGER",
  "SISONKE_DEPLOY_TX",
  "SISONKE_WASM_HASH",
  "SISONKE_ADMIN",
  "SISONKE_UPGRADE_DELAY",
  "SISONKE_SOURCE_REV",
];

function main() {
  const env = parseEnv(readFileSync(path.join(DEPLOYMENTS, "testnet.env"), "utf8"));
  const missing = KEYS.filter((k) => !env[k]);
  if (missing.length) throw new Error(`deployments/testnet.env is missing ${missing.join(", ")}`);
  const body = KEYS.map((k) => `  ${k}: ${JSON.stringify(env[k])},`).join("\n");
  writeFileSync(
    path.join(WEB, "lib/generated/deployment.ts"),
    `// Generated by scripts/sync-deployment.mjs from deployments/testnet.env. Do not edit.\n` +
      `// Every value is public.\nexport const deployment = {\n${body}\n} as const;\n`,
  );
  copyFileSync(path.join(DEPLOYMENTS, "testnet-e2e.json"), path.join(WEB, "lib/generated/proof.json"));
  console.log("Wrote lib/generated/deployment.ts and lib/generated/proof.json");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
