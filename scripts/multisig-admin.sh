#!/usr/bin/env bash
# Creates, configures and always fully verifies a native Stellar multisig
# account to be the sisonke-escrow admin: exactly N signer keys of weight 1,
# low = medium = high threshold = M (M >= 2), master key weight 0, and no
# other signers, so no single key (the account's own included) can act.
# Soroban checks the MEDIUM threshold for the admin's require_auth, and a
# HIGH-threshold set_options can't be run by one key either.
#
#   scripts/multisig-admin.sh                            # Testnet: 2-of-3 with local signer identities
#   NAME=sisonke-demo-admin scripts/multisig-admin.sh
#   SIGNERS=GAAA…,GBBB…,GCCC… THRESHOLD=2 scripts/multisig-admin.sh       # signers' own public keys
#   SIGNERS=GAAA…,GBBB…,GCCC… THRESHOLD=2 scripts/multisig-admin.sh verify G…ADMIN
#
# Env:
#   NETWORK     testnet (default) or mainnet
#   NAME        sisonke-admin: stellar CLI identity of the account (its master key
#               is used only to configure it, then disabled)
#   SIGNERS     either a count (Testnet only: creates local identities
#               <NAME>-signer-1 … <NAME>-signer-N), or a comma-separated list of the
#               signers' public keys (G…), each generated by its owner on their own device.
#               Off Testnet only public keys are accepted: this script never creates
#               signer keys there. Default: 3 on Testnet.
#   THRESHOLD   M, default 2; at least 2 and at most N
#   CONFIRM=1   required on mainnet. There the account must already exist and be funded.
#   RPC_URL, HORIZON_URL  override the network defaults
#
# `verify <ADDRESS>` only checks an existing account against SIGNERS / THRESHOLD
# (deploy.sh runs it off Testnet). Every run ends with the same full check and
# fails if the account differs in any way. Progress goes to stderr; the admin
# address is the only line on stdout, so ADMIN="$(scripts/multisig-admin.sh)" works.
set -euo pipefail

NETWORK="${NETWORK:-testnet}"
NAME="${NAME:-sisonke-admin}"
THRESHOLD="${THRESHOLD:-2}"
CONFIRM="${CONFIRM:-}"
COMMAND="${1:-setup}"

log() { echo "$*" >&2; }
die() { echo "✖ $*" >&2; exit 1; }
is_account_id() { [[ "$1" =~ ^G[A-Z2-7]{55}$ ]]; }

case "$NETWORK" in
  testnet)
    PASSPHRASE="Test SDF Network ; September 2015"
    RPC_URL="${RPC_URL:-https://soroban-testnet.stellar.org}"
    HORIZON_URL="${HORIZON_URL:-https://horizon-testnet.stellar.org}"
    SIGNERS="${SIGNERS:-3}"
    ;;
  mainnet)
    PASSPHRASE="Public Global Stellar Network ; September 2015"
    RPC_URL="${RPC_URL:?set RPC_URL for mainnet}"
    HORIZON_URL="${HORIZON_URL:-https://horizon.stellar.org}"
    SIGNERS="${SIGNERS:?set SIGNERS to the signers public keys, G…,G…,G…}"
    ;;
  *) die "Unknown NETWORK '$NETWORK'. Supported: testnet, mainnet." ;;
esac
NET=(--rpc-url "$RPC_URL" --network-passphrase "$PASSPHRASE")
command -v stellar >/dev/null || die "stellar CLI not found. Install: brew install stellar-cli"
command -v curl >/dev/null || die "curl not found"

# ------------------------------------------------------------- signer keys

KEYS=()
if [[ "$SIGNERS" =~ ^[0-9]+$ ]]; then
  [ "$NETWORK" = "testnet" ] ||
    die "Off Testnet SIGNERS must be the signers' own public keys (G…,G…), never keys generated here."
  for i in $(seq 1 "$SIGNERS"); do
    if [ "$COMMAND" != "verify" ] && ! stellar keys address "$NAME-signer-$i" >/dev/null 2>&1; then
      stellar keys generate "$NAME-signer-$i" >/dev/null
      log "✓ created local signer key $NAME-signer-$i (Testnet only)"
    fi
    KEYS+=("$(stellar keys address "$NAME-signer-$i")")
  done
else
  IFS=',' read -r -a KEYS <<<"$SIGNERS"
fi
N="${#KEYS[@]}"
for k in "${KEYS[@]}"; do
  is_account_id "$k" || die "Signer '$k' is not a G… public key"
done
[ "$(printf '%s\n' "${KEYS[@]}" | sort -u | wc -l | tr -d ' ')" = "$N" ] || die "SIGNERS lists the same key twice"
[[ "$THRESHOLD" =~ ^[0-9]+$ ]] || die "THRESHOLD must be a number"
# Every signer has weight 1, so the threshold must be reachable (or the account,
# and with it the admin role, is bricked) and at least 2 (or one key is the admin).
[ "$THRESHOLD" -ge 2 ] || die "THRESHOLD must be at least 2: a 1-of-N admin is a single key."
[ "$THRESHOLD" -le "$N" ] && [ "$N" -le 20 ] || die "Need 2 <= THRESHOLD <= N <= 20 (got $THRESHOLD-of-$N)"

# ------------------------------------------------------ Horizon parsing

account_json() { curl -fsS "$HORIZON_URL/accounts/$1" 2>/dev/null || true; }
# One {"weight":…,"key":"…","type":"…"} object per line.
signer_objects() {
  printf '%s' "$1" | tr -d '\n ' | sed -n 's/.*"signers":\[\([^]]*\)\].*/\1/p' | grep -oE '\{[^{}]*\}' || true
}
field() { printf '%s' "$1" | grep -oE "\"$2\":(\"[^\"]*\"|[0-9]+)" | head -1 | sed -E "s/^\"$2\"://; s/\"//g"; }
threshold_of() { printf '%s' "$1" | tr -d '\n ' | grep -oE "\"$2\":[0-9]+" | grep -oE '[0-9]+$' | head -1; }
weight_of() {
  local obj
  while IFS= read -r obj; do
    [ "$(field "$obj" key)" = "$2" ] && { field "$obj" weight; return; }
  done < <(signer_objects "$1")
  echo 0
}

# The full check. Prints every problem, fails if there is any.
verify_account() {
  local admin="$1" json problems=0 obj key weight type expected
  json="$(account_json "$admin")"
  [ -n "$json" ] || die "Account $admin not found on $NETWORK"
  log "checking $admin against $THRESHOLD-of-$N:"
  for t in low_threshold med_threshold high_threshold; do
    if [ "$(threshold_of "$json" "$t")" != "$THRESHOLD" ]; then
      log "  ✖ $t is $(threshold_of "$json" "$t"), expected $THRESHOLD"
      problems=$((problems + 1))
    fi
  done
  while IFS= read -r obj; do
    key="$(field "$obj" key)"
    weight="$(field "$obj" weight)"
    type="$(field "$obj" type)"
    if [ "$key" = "$admin" ]; then
      [ "$weight" = "0" ] || { log "  ✖ master key weight is $weight, expected 0"; problems=$((problems + 1)); }
      continue
    fi
    if [ "$type" != "ed25519_public_key" ]; then
      log "  ✖ unexpected signer of type $type: $key"
      problems=$((problems + 1))
      continue
    fi
    expected=""
    for k in "${KEYS[@]}"; do [ "$k" = "$key" ] && expected=1; done
    if [ -z "$expected" ]; then
      log "  ✖ unknown signer $key (weight $weight)"
      problems=$((problems + 1))
    elif [ "$weight" != "1" ]; then
      log "  ✖ signer $key has weight $weight, expected 1"
      problems=$((problems + 1))
    fi
  done < <(signer_objects "$json")
  for k in "${KEYS[@]}"; do
    if [ "$(weight_of "$json" "$k")" = "0" ]; then
      log "  ✖ expected signer $k is missing"
      problems=$((problems + 1))
    fi
  done
  [ "$problems" = "0" ] || die "$admin is not exactly the expected $THRESHOLD-of-$N multisig ($problems problem(s))."
  log "  ✓ master weight 0, thresholds $THRESHOLD/$THRESHOLD/$THRESHOLD, exactly these $N signers of weight 1"
}

# ------------------------------------------------------------- commands

if [ "$COMMAND" = "verify" ]; then
  ADMIN="${2:-}"
  is_account_id "$ADMIN" || die "usage: scripts/multisig-admin.sh verify <G… admin address>"
  verify_account "$ADMIN"
  echo "$ADMIN"
  exit 0
fi
[ "$COMMAND" = "setup" ] || die "usage: scripts/multisig-admin.sh [setup | verify <G…>]"
[ "$NETWORK" = "testnet" ] || [ "$CONFIRM" = "1" ] ||
  die "Refusing to configure a $NETWORK admin account without CONFIRM=1."

if ! stellar keys address "$NAME" >/dev/null 2>&1; then
  [ "$NETWORK" = "testnet" ] || die "Identity $NAME not found. Add the funded account's key: stellar keys add $NAME"
  stellar keys generate "$NAME" --network "$NETWORK" --fund >/dev/null
  log "✓ created and Friendbot-funded $NAME"
elif [ "$NETWORK" = "testnet" ]; then
  stellar keys fund "$NAME" --network "$NETWORK" >/dev/null 2>&1 || true
fi
ADMIN="$(stellar keys address "$NAME")"
is_account_id "$ADMIN" || die "Unexpected address for $NAME: '$ADMIN'"
JSON="$(account_json "$ADMIN")"
[ -n "$JSON" ] || die "Account $ADMIN not found on $NETWORK. Fund it first."
log "admin account: $ADMIN"

# Configuring needs the master key; once it is disabled, only verify.
if [ "$(weight_of "$JSON" "$ADMIN")" != "0" ]; then
  [ -z "$(signer_objects "$JSON" | grep -v "\"$ADMIN\"" || true)" ] ||
    die "$ADMIN already has other signers. Refusing to build on an unknown configuration; use a fresh account."
  for k in "${KEYS[@]}"; do
    stellar tx new set-options --source "$NAME" "${NET[@]}" --signer "$k" --signer-weight 1 >/dev/null
    log "✓ added signer $k, weight 1"
  done
  # Last step, signed by the master key for the final time.
  stellar tx new set-options --source "$NAME" "${NET[@]}" \
    --master-weight 0 --low-threshold "$THRESHOLD" --med-threshold "$THRESHOLD" \
    --high-threshold "$THRESHOLD" >/dev/null
  log "✓ thresholds $THRESHOLD/$THRESHOLD/$THRESHOLD, master key weight 0"
else
  log "master key already disabled: verifying only"
fi

verify_account "$ADMIN"
echo "$ADMIN"
